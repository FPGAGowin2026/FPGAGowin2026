#!/usr/bin/env python3
"""Build the RV32IMF firmware and generate the Gowin block-ROM package."""

import hashlib
import json
from pathlib import Path
import re
import subprocess


BOARD = Path(__file__).resolve().parents[1]
SOURCE = BOARD / 'src' / 'firmware'
OUTPUT = BOARD / 'impl' / 'firmware'
PACKAGE = BOARD / 'src' / 'softcore' / 'bx72_nav_boot_pkg.sv'
MARKER = '// Generated by tools/build_firmware.py; do not edit.'


def run(args):
    result = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if result.returncode:
        raise RuntimeError(' '.join(str(a) for a in args) + '\n' + result.stdout)
    return result.stdout


def source_hash():
    digest = hashlib.sha256()
    for path in sorted(SOURCE.iterdir()):
        if path.suffix in ('.c', '.h', '.S', '.ld'):
            digest.update(path.name.encode('utf-8') + b'\0')
            digest.update(path.read_bytes())
    return digest.hexdigest()


def main():
    if PACKAGE.exists() and not PACKAGE.read_text(encoding='utf-8').startswith(MARKER):
        raise RuntimeError(f'refusing to overwrite a non-generated file: {PACKAGE}')
    OUTPUT.mkdir(parents=True, exist_ok=True)
    before = source_hash()
    version = run(['riscv64-unknown-elf-gcc', '--version']).splitlines()[0]
    major = int(re.search(r'(\d+)\.\d+', version).group(1))
    march = 'rv32imf' if major < 11 else 'rv32imf_zicsr'
    flags = [f'-march={march}', '-mabi=ilp32f', '-Os', '-std=gnu11',
             '-ffp-contract=off', '-fsingle-precision-constant', '-ffreestanding',
             '-fno-builtin', '-fno-pic', '-fno-pie', '-fno-stack-protector',
             '-fno-asynchronous-unwind-tables', '-ffunction-sections', '-fdata-sections',
             '-msmall-data-limit=0', '-Wall', '-Wextra', '-Wconversion', '-Werror',
             '-fstack-usage']
    objects = []
    for source in [SOURCE / 'start.S', *sorted(SOURCE.glob('*.c'))]:
        obj = OUTPUT / (source.stem + '.o')
        run(['riscv64-unknown-elf-gcc', *flags, '-c', str(source), '-o', str(obj)])
        objects.append(str(obj))
    elf = OUTPUT / 'robot_firmware.elf'
    binary = OUTPUT / 'robot_firmware.bin'
    run(['riscv64-unknown-elf-gcc', *flags, '-nostdlib', '-nostartfiles',
         '-Wl,--gc-sections,--no-relax', f'-Wl,-Map={OUTPUT / "robot_firmware.map"}',
         '-T', str(SOURCE / 'link.ld'), *objects, '-lgcc', '-o', str(elf)])
    undefined = run(['riscv64-unknown-elf-nm', '-u', str(elf)])
    if undefined.strip():
        raise RuntimeError('undefined symbols: ' + undefined)
    symbols = {}
    for line in run(['riscv64-unknown-elf-nm', '-n', str(elf)]).splitlines():
        match = re.match(r'^([0-9a-fA-F]+)\s+\w\s+(\S+)$', line)
        if match:
            symbols[match.group(2)] = int(match.group(1), 16)
    static_ram = symbols['__bss_end'] - symbols['__data_start']
    stack = symbols['__stack_top'] - symbols['__stack_bottom']
    if static_ram > 32768 - stack or stack != 4096:
        raise RuntimeError('firmware static data overlaps the reserved RAM stack')
    run(['riscv64-unknown-elf-objcopy', '-O', 'binary', str(elf), str(binary)])
    image = binary.read_bytes()
    if not image or len(image) > 65536:
        raise RuntimeError(f'firmware does not fit in the 64 KiB ROM: {len(image)} bytes')
    if source_hash() != before:
        raise RuntimeError('firmware sources changed while compiling')
    capacity = max(16384, ((len(image) + 8191) // 8192) * 8192)
    padded = image.ljust(capacity, b'\0')
    lines = [MARKER, '// source SHA256=' + before,
             '// binary SHA256=' + hashlib.sha256(image).hexdigest(),
             'package bx72_nav_boot_pkg;',
             '    localparam integer ROM_ABI_VERSION = 2;',
             f'    localparam integer ROM_BYTES = {capacity};',
             '    localparam integer ROM_WORDS = ROM_BYTES / 4;',
             '    function automatic [31:0] boot_word(input [13:0] address);',
             '        begin', '            case (address)']
    for offset in range(0, capacity, 4):
        value = int.from_bytes(padded[offset:offset + 4], 'little')
        if value:
            lines.append(f"                14'd{offset // 4}: boot_word = 32'h{value:08x};")
    lines += ["                default: boot_word = 32'd0;", '            endcase',
              '        end', '    endfunction', 'endpackage', '']
    temp = PACKAGE.with_suffix('.sv.tmp')
    temp.write_text('\n'.join(lines), encoding='utf-8')
    temp.replace(PACKAGE)
    manifest = {'source_sha256': before, 'binary_sha256': hashlib.sha256(image).hexdigest(),
                'compiler': version, 'isa': march, 'abi': 'ilp32f',
                'rom_image_bytes': len(image), 'rom_capacity_bytes': capacity,
                'static_ram_bytes': static_ram, 'reserved_stack_bytes': stack,
                'ram_free_below_stack_bytes': 32768 - static_ram - stack}
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
